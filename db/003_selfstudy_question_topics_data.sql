  end if;

  select count(*) into v_n from _seed_v4 where review_status not in ('ORIGINAL_OK', 'CORRECTED');
  if v_n <> 0 then
    raise exception 'preflight: review_status 가 유효하지 않은 행이 % 건 있습니다.', v_n;
  end if;
end
$$;

