-- ---------------------------------------------------------------------
-- 6. 적재: INSERT ... ON CONFLICT (question_id) DO UPDATE. DELETE/TRUNCATE 없음.
--    created_at 은 SET 절에 포함하지 않아 기존 값을 그대로 유지한다(초기 INSERT 때는 컬럼 기본값 now() 적용).
