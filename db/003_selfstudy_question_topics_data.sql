declare
  v_n integer;
begin
  select count(*) into v_n from _seed_v4;
  if v_n <> 2475 then
    raise exception 'preflight: _seed_v4 행 수가 2475 가 아님니다 (%).', v_n;
  end if;

  select count(*) into v_n from (select question_id from _seed_v4 group by question_id having count(*) > 1) d;
  if v_n <> 0 then
    raise exception 'preflight: _seed_v4 안에 중복 question_id 가 % 건 있습니다.', v_n;
  end if;

  select count(*) into v_n from _seed_v4 where length(trim(learning_topic)) = 0;
  if v_n <> 0 then
