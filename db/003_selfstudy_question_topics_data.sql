  select count(*) into v_n
  from public.selfstudy_question_topics t
  join _seed_v4 s on s.question_id = t.question_id
  where t.review_status not in ('ORIGINAL_OK', 'CORRECTED');
  if v_n <> 0 then
    raise exception 'postcheck: review_status 가 유효하지 않은 행이 % 건 있습니다.', v_n;
  end if;
end
$$;

