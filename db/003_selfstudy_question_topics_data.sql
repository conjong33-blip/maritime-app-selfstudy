insert into public.selfstudy_question_topics (question_id, learning_topic, review_status)
select question_id, learning_topic, review_status from _seed_v4
on conflict (question_id) do update set
  learning_topic = excluded.learning_topic,
  review_status  = excluded.review_status,
  updated_at     = now();

